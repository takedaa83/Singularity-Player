const HANGUL_INITIAL = ['g', 'kk', 'n', 'd', 'tt', 'r', 'm', 'b', 'pp', 's', 'ss', '', 'j', 'jj', 'ch', 'k', 't', 'p', 'h'];
const HANGUL_MEDIAL = ['a', 'ae', 'ya', 'yae', 'eo', 'e', 'yeo', 'ye', 'o', 'wa', 'wae', 'oe', 'yo', 'u', 'wo', 'we', 'wi', 'yu', 'eu', 'ui', 'i'];
const HANGUL_FINAL = ['', 'k', 'k', 'ks', 'n', 'nj', 'nh', 't', 'l', 'lg', 'lm', 'lb', 'ls', 'lt', 'lp', 'lh', 'm', 'p', 'ps', 't', 't', 'ng', 't', 't', 'k', 't', 'p', 'h'];

/**
 * Checks if string contains Japanese, Korean, or Chinese characters.
 */
export function hasCjkCharacters(text: string): boolean {
  return /[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uac00-\ud7af]/.test(text);
}

/**
 * Converts Japanese Kana or Korean Hangul text into Romanized phonetic text.
 */
export function romanizeText(text: string): string {
  if (!text) return '';

  let result = '';
  let i = 0;

  while (i < text.length) {
    const char = text[i];
    const code = char.charCodeAt(0);

    // 1. Korean Hangul Syllables (AC00 - D7AF)
    if (code >= 0xac00 && code <= 0xd7af) {
      const syllableIndex = code - 0xac00;
      const initialIndex = Math.floor(syllableIndex / 588);
      const medialIndex = Math.floor((syllableIndex % 588) / 28);
      const finalIndex = syllableIndex % 28;

      result += HANGUL_INITIAL[initialIndex] + HANGUL_MEDIAL[medialIndex] + HANGUL_FINAL[finalIndex];
      i++;
      continue;
    }

    // 2. Japanese Multi-character Kana compounds (e.g. きゃ, チュ)
    if (i < text.length - 1) {
      const twoChar = text.substring(i, i + 2);
      if (KANA_ROMAJI_MAP[twoChar]) {
        result += KANA_ROMAJI_MAP[twoChar];
        i += 2;
        continue;
      }
    }

    // 3. Japanese Single Kana
    if (KANA_ROMAJI_MAP[char]) {
      result += KANA_ROMAJI_MAP[char];
      i++;
      continue;
    }

    // Sokuon (っ / ッ) small tsu handling: double next consonant
    if (char === 'っ' || char === 'ッ') {
      if (i < text.length - 1) {
        const nextChar = text[i + 1];
        const nextRomaji = KANA_ROMAJI_MAP[nextChar] || '';
        if (nextRomaji && nextRomaji[0]) {
          result += nextRomaji[0];
        }
      }
      i++;
      continue;
    }

    // Default: retain character (Latin, punctuation, Kanji)
    result += char;
    i++;
  }

  return result;
}
